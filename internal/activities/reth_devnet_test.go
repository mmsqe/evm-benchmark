// TestRethRunScriptFormat pins both launchers byte-for-byte: the flags are the
// contract with `reth node`. Pools are sized for both nodes' load.
func TestRethRunScriptFormat(t *testing.T) {
	spec := messages.BenchmarkSpec{
		RethBin:       "/opt/reth",
		RethBasePort:  9500,
		RethGasLimit:  1_000_000_000,
		RethBlockTime: "2s",
		NumAccounts:   500,
		NumTxs:        40,
	}
	pool := `  '--txpool.max-account-slots' \
  '40' \
  '--txpool.pending-max-count' \
  '40000' \
  '--txpool.pending-max-size' \
  '20' \
  '--txpool.queued-max-count' \
  '40000' \
  '--txpool.queued-max-size' \
  '20'
`
	shared := func(http, auth, p2p, metrics string) string {
		return `  'node' \
  '--chain' \
  './genesis.json' \
  '--datadir' \
  '.' \
  '--log.file.directory' \
  './logs' \
  '--http' \
  '--http.addr' \
  '127.0.0.1' \
  '--http.port' \
  '` + http + `' \
  '--http.api' \
  'eth,net,web3,txpool' \
  '--authrpc.port' \
  '` + auth + `' \
  '--addr' \
  '127.0.0.1' \
  '--port' \
  '` + p2p + `' \
  '--disable-discovery' \
  '--nat' \
  'none' \
  '--metrics' \
  '127.0.0.1:` + metrics + `' \
  '--ipcdisable' \
`
	}

	wantProducer := `#!/bin/sh
# auto-generated by evm-benchmark

cd "$(dirname "$0")"

exec '/opt/reth' \
` + shared("9502", "9501", "9500", "9504") + `  '--dev' \
  '--dev.block-time' \
  '2000ms' \
  '--ws' \
  '--ws.addr' \
  '127.0.0.1' \
  '--ws.port' \
  '9503' \
  '--ws.api' \
  'eth' \
  '--p2p-secret-key-hex' \
  'adcdc02f905cfb8540e6dfb2d9453c2e7ded6b4ede48315205daaa43f73178e1' \
  '--builder.gaslimit' \
  '1000000000' \
` + pool
	if got := rethTestLauncher(t, spec, rethTestProducer).render(); got != wantProducer {
		t.Errorf("producer run.sh mismatch:\n--- got ---\n%s\n--- want ---\n%s", got, wantProducer)
	}

	wantFullnode := `#!/bin/sh
# auto-generated by evm-benchmark

cd "$(dirname "$0")"

until curl -s -o /dev/null 'http://127.0.0.1:9503'; do sleep 0.2; done

exec '/opt/reth' \
` + shared("9507", "9506", "9505", "9509") + `  '--trusted-peers' \
  'enode://92eeefb9a645ebeef877ef150c0f2bf6497bbf65c7b4c86ec12acaf814d98746c180a287ae95e935a6f033f665266a146bdad98a4c6fe1be4582300139a66084@127.0.0.1:9500' \
  '--debug.rpc-consensus-url' \
  'ws://127.0.0.1:9503' \
` + pool
	if got := rethTestLauncher(t, spec, rethTestFullnode).render(); got != wantFullnode {
		t.Errorf("fullnode run.sh mismatch:\n--- got ---\n%s\n--- want ---\n%s", got, wantFullnode)
	}
}

// TestRethProducerEnodeMatchesKey guards the link between the launchers: the
// enode fullnodes dial must belong to the key the producer starts with.
func TestRethProducerEnodeMatchesKey(t *testing.T) {
	enode := rethProducerEnode(messages.BenchmarkSpec{})
	id := strings.TrimSuffix(strings.TrimPrefix(enode, "enode://"), "@127.0.0.1:9500")
	pub, err := crypto.UnmarshalPubkey(common.FromHex("04" + id))
	if err != nil {
		t.Fatalf("enode %s carries no public key: %v", enode, err)
	}
	if !pub.Equal(&rethProducerKey.PublicKey) {
		t.Errorf("enode %s is not the producer key's", enode)
	}
}

// TestRethLauncherDefaults guards against inventing settings: an unset gas
// limit keeps reth's builder target, and the block time defaults to 1s.
func TestRethLauncherDefaults(t *testing.T) {
	joined := rethTestLauncher(t, messages.BenchmarkSpec{}, rethTestProducer).render()
	if strings.Contains(joined, "--builder.gaslimit") {
		t.Errorf("--builder.gaslimit passed although unset:\n%s", joined)
	}
	if !strings.Contains(joined, "'--dev.block-time' \\\n  '1000ms'") {
		t.Errorf("block time does not default to 1s:\n%s", joined)
	}
}

// TestRethLauncherAppendsExtra pins the extra flags: reth_node_args reach every
// node, reth_fullnode_args only fullnodes and after the shared ones.
func TestRethLauncherAppendsExtra(t *testing.T) {
	spec := messages.BenchmarkSpec{
		RethNodeArgs:     []string{"--engine.cross-block-cache-size", "1024"},
		RethFullnodeArgs: []string{"--engine.prewarm-reuse"},
	}
	producer := rethTestLauncher(t, spec, rethTestProducer).Args
	if got := strings.Join(producer[len(producer)-2:], " "); got != "--engine.cross-block-cache-size 1024" {
		t.Errorf("producer extra flags = %q, want reth_node_args only", got)
	}
	fullnode := rethTestLauncher(t, spec, rethTestFullnode).Args
	if got := strings.Join(fullnode[len(fullnode)-3:], " "); got != "--engine.cross-block-cache-size 1024 --engine.prewarm-reuse" {
		t.Errorf("fullnode extra flags = %q, want reth_node_args then reth_fullnode_args", got)
	}
}

