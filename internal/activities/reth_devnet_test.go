// TestRethGenesisFundsSigner is the load-bearing check: every account the
// shared signer uses must be funded, natively and in the token, or its
// transactions can never pay.
func TestRethGenesisFundsSigner(t *testing.T) {
	spec := messages.BenchmarkSpec{
		NumAccounts:          3,
		NumTxs:               2,
		EVMChainID:           1337,
		GasPriceWei:          1_000_000_000,
		ERC20TransferGas:     60_000,
		TxType:               messages.ERC20TransferTx,
		ERC20ContractAddress: rethTokenAddress.Hex(),
		BaseMnemonic:         rethTestMnemonic,
	}
	nodes := []messages.NodeTarget{rethTestProducer, rethTestFullnode}
	genesis, err := rethGenesis(spec, nodes)
	if err != nil {
		t.Fatalf("rethGenesis: %v", err)
	}
	alloc := genesis["alloc"].(map[string]interface{})
	token, ok := alloc[strings.ToLower(rethTokenAddress.Hex())].(map[string]interface{})
	if !ok {
		t.Fatalf("token not deployed at %s", rethTokenAddress.Hex())
	}
	storage := token["storage"].(map[string]interface{})
	for _, node := range nodes {
		raws, err := bench.GenerateSignedTxs(spec, node.GlobalSeq)
		if err != nil {
			t.Fatalf("GenerateSignedTxs: %v", err)
		}
		for _, raw := range raws {
			sender, err := senderOf(raw, spec.EVMChainID)
			if err != nil {
				t.Fatalf("recover sender: %v", err)
			}
			if _, ok := alloc[strings.ToLower(sender.Hex())]; !ok {
				t.Errorf("node %d signs from unfunded account %s", node.GlobalSeq, sender.Hex())
			}
			if storage[rethTokenBalanceSlot(sender).Hex()] != common.BigToHash(rethTokenBalance).Hex() {
				t.Errorf("node %d signs from %s, which holds no tokens", node.GlobalSeq, sender.Hex())
			}
		}
	}
	if storage[rethTokenBalanceSlot(bench.HotRecipient).Hex()] != common.BigToHash(big.NewInt(1)).Hex() {
		t.Error("hot recipient's token balance not seeded")
	}
}

// TestRethGenesisTokenOnlyForItsLoad: native transfers need no token, and an
// operator's own token address comes with its own code.
func TestRethGenesisTokenOnlyForItsLoad(t *testing.T) {
	for name, spec := range map[string]messages.BenchmarkSpec{
		"simple transfers": {TxType: messages.SimpleTransferTx},
		"own token":        {TxType: messages.ERC20TransferTx, ERC20ContractAddress: "0x1000000000000000000000000000000000000000"},
	} {
		spec.NumAccounts = 1
		spec.BaseMnemonic = rethTestMnemonic
		genesis, err := rethGenesis(spec, []messages.NodeTarget{rethTestProducer})
		if err != nil {
			t.Fatalf("%s: rethGenesis: %v", name, err)
		}
		if _, ok := genesis["alloc"].(map[string]interface{})[strings.ToLower(rethTokenAddress.Hex())]; ok {
			t.Errorf("%s: token deployed although the load does not use it", name)
		}
	}
}

// TestRethGenesisPatchWins pins the gasLimit encoding (a hex quantity) and that
// genesis_patch overrides the family's genesis.
func TestRethGenesisPatchWins(t *testing.T) {
	spec := messages.BenchmarkSpec{NumAccounts: 1, BaseMnemonic: rethTestMnemonic, RethGasLimit: 1_000_000_000}
	genesis, err := rethGenesis(spec, []messages.NodeTarget{rethTestProducer})
	if err != nil {
		t.Fatal(err)
	}
	if got := genesis["gasLimit"]; got != "0x3b9aca00" {
		t.Errorf("gasLimit = %v, want the hex quantity 0x3b9aca00", got)
	}
	spec.GenesisPatch = map[string]interface{}{"gasLimit": "0x1"}
	if genesis, err = rethGenesis(spec, []messages.NodeTarget{rethTestProducer}); err != nil {
		t.Fatal(err)
	}
	if got := genesis["gasLimit"]; got != "0x1" {
		t.Errorf("genesis_patch must override the gas limit, got %v", got)
	}
}

// TestRethTokenCode checks the hand-assembled token for the mistakes editing it
// invites: every jump lands on a JUMPDEST, both selectors are dispatched, and
// the code does not end inside a push.
func TestRethTokenCode(t *testing.T) {
	const (
		push0    = 0x5f
		push1    = 0x60
		push32   = 0x7f
		jump     = 0x56
		jumpi    = 0x57
		jumpdest = 0x5b
	)
	code := rethTokenCode
	jumpdests := map[int]bool{}
	var jumps []int
	pc := 0
	for ; pc < len(code); pc++ {
		op := code[pc]
		if op == jumpdest {
			jumpdests[pc] = true
		}
		if op == push1 && pc+2 < len(code) && (code[pc+2] == jump || code[pc+2] == jumpi) {
			jumps = append(jumps, int(code[pc+1]))
		}
		if op > push0 && op <= push32 {
			pc += int(op - push0)
		}
	}
	if pc != len(code) {
		t.Errorf("code ends inside a push: decoded to %d of %d bytes", pc, len(code))
	}
	if len(jumps) != 3 {
		t.Errorf("found %d jumps, want transfer, balanceOf and the balance check", len(jumps))
	}
	for _, target := range jumps {
		if !jumpdests[target] {
			t.Errorf("jump to 0x%02x, which is not a JUMPDEST", target)
		}
	}
	for _, selector := range []string{"a9059cbb", "70a08231"} {
		if !strings.Contains(common.Bytes2Hex(code), "63"+selector) {
			t.Errorf("selector %s not dispatched", selector)
		}
	}
}

func TestRethValidate(t *testing.T) {
	ok := messages.BenchmarkSpec{RunnerType: "local", Validators: 1, Fullnodes: 2, StartNode: true, RethBin: "reth"}
	if err := (rethRuntime{}).Validate(ok); err != nil {
		t.Fatalf("valid spec refused: %v", err)
	}
	for name, mutate := range map[string]func(*messages.BenchmarkSpec){
		"docker":           func(s *messages.BenchmarkSpec) { s.RunnerType = "docker" },
		"two producers":    func(s *messages.BenchmarkSpec) { s.Validators = 2 },
		"no binary":        func(s *messages.BenchmarkSpec) { s.RethBin = "" },
		"sub-second block": func(s *messages.BenchmarkSpec) { s.RethBlockTime = "500ms" },
		"bad block time":   func(s *messages.BenchmarkSpec) { s.RethBlockTime = "soon" },
	} {
		spec := ok
		mutate(&spec)
		if err := (rethRuntime{}).Validate(spec); err == nil {
			t.Errorf("%s: accepted", name)
		}
	}
}

func TestRethSummarizeMetrics(t *testing.T) {
	scrape := []byte(`# HELP reth_consensus_engine_beacon_new_payload_latency
reth_consensus_engine_beacon_new_payload_latency{quantile="0.5"} 0.2
reth_consensus_engine_beacon_new_payload_latency_sum 6.5
reth_consensus_engine_beacon_new_payload_latency_count 40
reth_sync_execution_execution_histogram_sum 4
reth_sync_execution_gas_processed_total 2000000000
reth_sync_prewarm_reuse_reused_transactions 900
reth_sync_prewarm_reuse_missing_transactions 60
reth_sync_prewarm_reuse_stale_transactions 40
`)
	lines, err := (rethRuntime{}).SummarizeMetrics(scrape)
	if err != nil {
		t.Fatalf("SummarizeMetrics: %v", err)
	}
	want := "engine_summary new_payloads=40 new_payload_seconds=6.500 execution_seconds=4.000 gas=2000000000 execution_mgas_per_s=500.0\n" +
		"reuse_summary reused=900 missing=60 stale=40"
	if got := strings.Join(lines, "\n"); got != want {
		t.Errorf("summary =\n%s\nwant\n%s", got, want)
	}

	renamed := []byte(strings.ReplaceAll(string(scrape), "reth_sync_prewarm_reuse_stale_transactions", "renamed"))
	if _, err := (rethRuntime{}).SummarizeMetrics(renamed); err == nil {
		t.Error("scrape without the stale counter accepted")
	}
}
